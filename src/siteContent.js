function matchesContentShape(value, template) {
  if (typeof template === 'string') return typeof value === 'string';
  if (Array.isArray(template)) {
    return (
      Array.isArray(value) &&
      (template.length === 0 ||
        value.every((item) => matchesContentShape(item, template[0])))
    );
  }
  if (
    template !== null &&
    typeof template === 'object' &&
    !Array.isArray(template)
  ) {
    return (
      value !== null &&
      typeof value === 'object' &&
      !Array.isArray(value) &&
      Object.keys(template).every(
        (key) =>
          Object.prototype.hasOwnProperty.call(value, key) &&
          matchesContentShape(value[key], template[key])
      )
    );
  }
  return typeof value === typeof template;
}

export function isValidSiteContent(value) {
  if (!matchesContentShape(value, DEFAULT_SITE_CONTENT)) return false;

  const imageNames = [
    value.brand.logoImage,
    value.story.image,
    ...value.rooms.items.map((room) => room.image),
    ...value.gallery.items.map((picture) => picture.image),
    ...value.hero.slides.map((slide) => slide.image),
  ];
  let mapUrl;
  try {
    mapUrl = new URL(value.contact.mapUrl);
  } catch {
    return false;
  }
  return (
    /^\d+$/.test(value.contact.whatsappNumber) &&
    mapUrl.protocol === 'https:' &&
    imageNames.every((name) => /^[A-Za-z0-9_-]+$/.test(name))
  );
}
